#!/usr/bin/env python3
"""aicfg: sync this repo's skills, agents, commands, rules, and hooks into AI harnesses.

Usage:
  aicfg.py status     show what would change (default, no writes)
  aicfg.py apply      render rules, create/refresh symlinks, merge settings
  aicfg.py validate   check frontmatter and cross-references (used in CI)

Safety: never overwrites a real file or a symlink pointing outside this repo.
Those are reported as CONFLICT and left alone for you to resolve. Settings files
are merged (only entries owned by this repo are replaced) and backed up first.
"""
from __future__ import annotations

import copy
import json
import os
import re
import shutil
import sys
import tomllib
from dataclasses import dataclass
from datetime import datetime, timezone
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
DIST = REPO / "dist"
RENDERED_INSTRUCTIONS = DIST / "instructions.md"

# Hook commands containing this marker are owned by this repo and replaced on merge.
OWNED_HOOK_MARKER = "/hooks/ai-config/"

KNOWN_TOOLS = {
    "Read", "Write", "Edit", "MultiEdit", "Grep", "Glob", "Bash",
    "WebFetch", "WebSearch", "NotebookEdit", "TodoWrite",
}
KNOWN_MODELS = {"haiku", "sonnet", "opus", "inherit"}
SKILL_NAME = re.compile(r"^[a-z0-9]+(-[a-z0-9]+)*$")


# ---------- config ----------

def load_harnesses() -> dict[str, dict]:
    config = tomllib.loads((REPO / "harnesses.toml").read_text())
    local = REPO / "harnesses.local.toml"
    if local.exists():
        for name, overrides in tomllib.loads(local.read_text()).items():
            config.setdefault(name, {}).update(overrides)
    return {name: h for name, h in config.items() if h.get("enabled", True)}


def expand(path: str) -> Path:
    return Path(os.path.expandvars(os.path.expanduser(path)))


def tilde(path: Path) -> str:
    return str(path).replace(str(Path.home()), "~", 1)


# ---------- sources ----------

def skills() -> list[Path]:
    return sorted(p for p in (REPO / "skills").iterdir() if (p / "SKILL.md").is_file())


def markdown_files(folder: str) -> list[Path]:
    return sorted(
        p for p in (REPO / folder).glob("*.md")
        if p.name != "README.md" and not p.name.endswith(".local.md")
    )


def render_instructions() -> str:
    # Shared rules first, then gitignored machine-local rules (rules/*.local.md).
    rules_dir = REPO / "rules"
    rule_files = markdown_files("rules") + sorted(rules_dir.glob("*.local.md"))
    parts = ["<!-- GENERATED by ai-config from rules/*.md. Edit the repo, not this file. -->"]
    parts += [rule.read_text().strip() for rule in rule_files]
    return "\n\n".join(parts) + "\n"


# ---------- planning ----------

@dataclass
class Link:
    harness: str
    dest: Path
    source: Path

    def state(self) -> str:
        if self.dest.is_symlink():
            target = Path(os.readlink(self.dest))
            if target == self.source:
                return "ok"
            return "update" if _inside_repo(target) else "conflict"
        return "conflict" if self.dest.exists() else "create"


@dataclass
class SettingsMerge:
    harness: str
    dest: Path
    fragment: Path


def _inside_repo(path: Path) -> bool:
    try:
        path.resolve().relative_to(REPO)
        return True
    except ValueError:
        return False


def plan() -> tuple[list[Link], list[Path], list[SettingsMerge]]:
    links: list[Link] = []
    merges: list[SettingsMerge] = []
    managed_dirs: set[Path] = set()
    for name, h in load_harnesses().items():
        if "skills" in h:
            d = expand(h["skills"])
            managed_dirs.add(d)
            links += [Link(name, d / s.name, s) for s in skills()]
        for kind in ("agents", "commands"):
            if kind in h:
                d = expand(h[kind])
                managed_dirs.add(d)
                links += [Link(name, d / f.name, f) for f in markdown_files(kind)]
        if "instructions" in h:
            links.append(Link(name, expand(h["instructions"]), RENDERED_INSTRUCTIONS))
        if "hooks_dir" in h:
            links.append(Link(name, expand(h["hooks_dir"]), REPO / "overrides" / name / "hooks"))
        fragment = REPO / "overrides" / name / "settings.fragment.json"
        if "settings" in h and fragment.is_file():
            merges.append(SettingsMerge(name, expand(h["settings"]), fragment))

    # Stale: dangling symlinks in managed dirs that point into this repo.
    wanted = {link.dest for link in links}
    stale = [
        p
        for d in managed_dirs if d.is_dir()
        for p in d.iterdir()
        if p.is_symlink() and p not in wanted and not p.exists()
        and _inside_repo(Path(os.readlink(p)))
    ]
    return links, stale, merges


# ---------- settings merge ----------

def _owned(group: dict) -> bool:
    return any(OWNED_HOOK_MARKER in str(h.get("command", "")) for h in group.get("hooks", []))


def merge_settings(current: dict, fragment: dict) -> dict:
    """Return current with this repo's hook groups replaced by the fragment's.

    Hook groups owned by other tools/plugins are kept in place and order. Only the
    `hooks` key of the fragment is merged; other settings stay under user control.
    """
    merged = copy.deepcopy(current)
    hooks = merged.setdefault("hooks", {})
    wanted = fragment.get("hooks", {})
    for event in set(hooks) | set(wanted):
        kept = [g for g in hooks.get(event, []) if not _owned(g)]
        groups = kept + copy.deepcopy(wanted.get(event, []))
        if groups:
            hooks[event] = groups
        else:
            hooks.pop(event, None)
    if not hooks and "hooks" not in current:
        merged.pop("hooks")
    return merged


def settings_change(m: SettingsMerge) -> tuple[str, dict | None]:
    """Return (state, merged) where state is ok | merge | conflict."""
    try:
        current = json.loads(m.dest.read_text()) if m.dest.exists() else {}
    except json.JSONDecodeError:
        return "conflict", None
    merged = merge_settings(current, json.loads(m.fragment.read_text()))
    return ("ok" if merged == current else "merge"), merged


# ---------- commands ----------

def cmd_sync(apply: bool) -> int:
    if apply:
        DIST.mkdir(exist_ok=True)
        RENDERED_INSTRUCTIONS.write_text(render_instructions())

    links, stale, merges = plan()
    conflicts = changes = 0
    for link in links:
        state = link.state()
        if state == "ok":
            continue
        print(f"{state.upper():9} {link.harness:9} {tilde(link.dest)}")
        if state == "conflict":
            conflicts += 1
            continue
        changes += 1
        if apply:
            link.dest.parent.mkdir(parents=True, exist_ok=True)
            if link.dest.is_symlink():
                link.dest.unlink()
            link.dest.symlink_to(link.source)
    for p in stale:
        changes += 1
        print(f"{'PRUNE':9} {'':9} {tilde(p)}")
        if apply:
            p.unlink()
    for m in merges:
        state, merged = settings_change(m)
        if state == "ok":
            continue
        print(f"{state.upper():9} {m.harness:9} {tilde(m.dest)}"
              + ("  (invalid JSON, fix by hand)" if state == "conflict" else "  (hooks)"))
        if state == "conflict":
            conflicts += 1
            continue
        changes += 1
        if apply:
            m.dest.parent.mkdir(parents=True, exist_ok=True)
            if m.dest.exists():
                stamp = datetime.now(timezone.utc).strftime("%Y%m%dT%H%M%SZ")
                shutil.copy2(m.dest, m.dest.with_name(f"{m.dest.name}.bak-aicfg-{stamp}"))
            m.dest.write_text(json.dumps(merged, indent=2) + "\n")

    if not changes and not conflicts:
        print("Everything in sync.")
    elif not apply and changes:
        print("\nDry run. Run `apply` to write.")
    if conflicts:
        print(f"\n{conflicts} conflict(s): existing files not managed by this repo. "
              "Move them into the repo (or delete them), then re-run.")
    return 1 if conflicts else 0


# ---------- validation ----------

def frontmatter(path: Path) -> dict[str, str]:
    lines = path.read_text().splitlines()
    if not lines or lines[0].strip() != "---":
        return {}
    meta = {}
    for line in lines[1:]:
        if line.strip() == "---":
            return meta
        if ":" in line and not line.startswith((" ", "\t")):
            key, _, value = line.partition(":")
            meta[key.strip()] = value.split(" #", 1)[0].strip()
    return {}  # unterminated frontmatter


def _markdown_under(root: Path) -> list[Path]:
    found = []
    for dirpath, _dirs, files in os.walk(root):  # does not follow symlinked dirs (skills/*/roles)
        found += [Path(dirpath) / f for f in files if f.endswith(".md")]
    return sorted(found)


FENCE = re.compile(r"^(```|~~~).*?^\1", re.S | re.M)
MD_LINK = re.compile(r"\[[^\]]*\]\(([^)\s]+)\)")
AGENT_TAG = re.compile(r"\[agent:\s*([a-z0-9-]+)\]")
SKILL_MENTION = re.compile(r"`([a-z0-9-]+)` skill")


def _check_references(path: Path, agent_names: set[str], skill_names: set[str]) -> list[str]:
    rel = path.relative_to(REPO)
    text = FENCE.sub("", path.read_text())
    errors = []
    for target in MD_LINK.findall(text):
        if re.match(r"^[a-z]+:", target) or target.startswith("#") or "<" in target:
            continue
        if not (path.parent / target.split("#", 1)[0]).exists():
            errors.append(f"{rel}: broken link `{target}`")
    errors += [f"{rel}: unknown agent `{a}`" for a in AGENT_TAG.findall(text) if a not in agent_names]
    errors += [f"{rel}: unknown skill `{s}`" for s in SKILL_MENTION.findall(text) if s not in skill_names]
    return errors


def cmd_validate() -> int:
    errors = []
    agent_files = markdown_files("agents")
    agent_names = {f.stem for f in agent_files}
    skill_names = {s.name for s in skills()}

    for s in skills():
        meta = frontmatter(s / "SKILL.md")
        if meta.get("name") != s.name:
            errors.append(f"skills/{s.name}/SKILL.md: `name` must equal the directory name")
        if not SKILL_NAME.match(s.name) or len(s.name) > 64:
            errors.append(f"skills/{s.name}: name must be lowercase-hyphenated, 64 chars max")
        description = meta.get("description", "")
        if not description:
            errors.append(f"skills/{s.name}/SKILL.md: missing `description`")
        elif len(description) > 1024:
            errors.append(f"skills/{s.name}/SKILL.md: `description` over 1024 chars")
        for dirpath, dirs, files in os.walk(s):
            for entry in dirs + files:
                p = Path(dirpath) / entry
                if p.is_symlink() and not p.exists():
                    errors.append(f"{p.relative_to(REPO)}: dangling symlink")
        for md in _markdown_under(s):
            errors += _check_references(md, agent_names, skill_names)

    for f in agent_files:
        meta = frontmatter(f)
        if meta.get("name") != f.stem:
            errors.append(f"agents/{f.name}: `name` must equal the file name")
        if not meta.get("description"):
            errors.append(f"agents/{f.name}: missing `description`")
        tools = {t.strip() for t in meta.get("tools", "").split(",") if t.strip()}
        errors += [f"agents/{f.name}: unknown tool `{t}`" for t in sorted(tools - KNOWN_TOOLS)]
        if meta.get("model") and meta["model"] not in KNOWN_MODELS:
            errors.append(f"agents/{f.name}: unknown model `{meta['model']}`")
        errors += _check_references(f, agent_names, skill_names)

    for f in markdown_files("commands"):
        if not frontmatter(f).get("description"):
            errors.append(f"commands/{f.name}: missing `description`")
        errors += _check_references(f, agent_names, skill_names)

    for fragment in sorted((REPO / "overrides").glob("*/settings.fragment.json")):
        try:
            json.loads(fragment.read_text())
        except json.JSONDecodeError as e:
            errors.append(f"{fragment.relative_to(REPO)}: invalid JSON ({e})")

    for e in errors:
        print(f"ERROR {e}")
    counts = (f"{len(skill_names)} skills, {len(agent_names)} agents, "
              f"{len(markdown_files('commands'))} commands")
    print(f"{'FAILED' if errors else 'OK'}: {counts}")
    return 1 if errors else 0


def main(argv: list[str]) -> int:
    cmd = argv[1] if len(argv) > 1 else "status"
    if cmd in ("status", "apply"):
        return cmd_sync(apply=cmd == "apply")
    if cmd == "validate":
        return cmd_validate()
    print(__doc__)
    return 2


if __name__ == "__main__":
    sys.exit(main(sys.argv))
